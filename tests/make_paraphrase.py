def main():
    if DST.exists():
        shutil.rmtree(DST)
    shutil.copytree(SRC / "packages", DST / "packages")
    shutil.copy(SRC / "answers_public.json", DST / "answers_public.json")
    shutil.copy(SRC / "check.py", DST / "check.py")
    rows = list(csv.DictReader((SRC / "questions.csv").read_text(encoding="utf-8-sig").splitlines(), delimiter=";"))
    with open(DST / "questions.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "package", "question"], delimiter=";")
        w.writeheader()
        for r in rows:
            w.writerow({"id": r["id"], "package": r["package"], "question": PARA[r["question"]]})
    print(f"Готово: {DST} ({len(rows)} вопросов)")


if __name__ == "__main__":
    main()
