def main():
    if DST.exists():
        shutil.rmtree(DST)
    shutil.copytree(SRC / "packages", DST / "packages")
    shutil.copy(SRC / "check.py", DST / "check.py")
    gold = []
    with open(DST / "questions.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["id", "package", "question"])
        for qid, q, typ, (status, kind, exp, quote, file) in Q:
            w.writerow([qid, qid.split("-")[0], q])
            g = {"id": qid, "package": qid.split("-")[0], "type": typ, "status": status, "expected": exp,
                 "quote": quote, "file": file}
            if kind:
                g["kind"] = kind
            gold.append(g)
    (DST / "answers_public.json").write_text(json.dumps(gold, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Готово: {DST} ({len(Q)} вопросов)")


if __name__ == "__main__":
    main()
